print(12.345)   #顯示浮點數常值12.345的值(直接把浮點印出來)
print(1.2345e2)   #顯示浮點數常值12.345e2的值123.45(e他代表*10的幾次方=>1.2345*10的2次方=>1.2345*100)
print(1.2345e8)   #顯示浮點數常值12.345e8的值123450000.0(1.2345*10的8次方=>1.2345*100000000；因為它仍然是float小數點)
print(1.2345e-2)   #顯示浮點數常值12.345e-2的值0.012345(-他代表/=>1.2345/10的2次方=>1.2345/100)
#浮點數 = 有小數字點的數字
